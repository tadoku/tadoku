const base = 'http://127.0.0.1:33946'
const directory = new URL('./', import.meta.url)
const browser = await openBrowser()
const journeys = []

async function check(name, run, width = 1440) {
  const context = await browser.newContext({ viewport: { width, height: 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await run(page)
    assert.deepEqual(errors, [], 'No browser JavaScript errors')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'No document overflow')
    const dismiss = page.getByRole('button', { name: 'Dismiss notification' })
    if (await dismiss.count()) {
      await dismiss.first().click()
      await dismiss.waitFor({ state: 'detached' })
    }
    const screenshot = `evidence/contests/journey-${name}.png`
    await page.screenshot({ path: new URL(screenshot, directory).pathname, fullPage: true })
    journeys.push({ name, width, status: 'pass', jsErrors: errors, screenshot })
  } catch (error) {
    journeys.push({ name, width, status: 'fail', error: error.message, jsErrors: errors })
  } finally { await context.close() }
  console.log(`${name}: ${journeys.at(-1).status}`)
}

