import { randomUUID } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { test, expect } from '@playwright/test'

// Failure modes: missing SSR controls, lost pre-hydration input, rejected native
// submissions, wrong-password errors, missing session persistence and unsafe return URLs.
test('rendered account forms and progressive enhancement', async ({ browser, page }, testInfo) => {
  const stateFile = process.env.AUTHV2_READER_STATE_FILE
  const initialPassword = stateFile && existsSync(stateFile) ? readFileSync(stateFile, 'utf8') : process.env.AUTHV2_READER_PASSWORD || 'tadoku'
  await page.goto('/login')
  await expect(page.getByRole('heading', { name: 'Log in', exact: true })).toBeVisible()
  await expect(page.getByLabel('Email')).toBeEditable()
  await expect(page.getByLabel('Password')).toBeEditable()
  await page.getByLabel('Email').fill(`unknown-${randomUUID()}@example.test`)
  await page.getByLabel('Password').fill('incorrect-password')
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(page.getByText('The email or password is incorrect.')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('login-error.png'), fullPage: true })

  const context = await browser.newContext({ baseURL: testInfo.project.use.baseURL, javaScriptEnabled: false })
  const native = await context.newPage()
  const email = `w2-${randomUUID()}@example.test`
  const password = `Reading-${randomUUID()}`
  await native.goto('/registration')
  await expect(native.getByRole('heading', { name: 'Create an account' })).toBeVisible()
  await native.getByLabel('Email').fill(email)
  await native.getByLabel('Display name').fill('W2 Reader')
  await native.getByLabel('Password').fill(password)
  await native.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(native.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await expect(native.getByLabel('Email')).toHaveValue(email)
  await native.reload()
  await expect(native.getByLabel('Display name')).toHaveValue('W2 Reader')
  await native.getByRole('button', { name: 'Log out', exact: true }).click()
  await expect(native.getByRole('heading', { name: 'Log in', exact: true })).toBeVisible()
  await native.getByLabel('Email').fill(email)
  await native.getByLabel('Password').fill(password)
  await native.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(native.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await native.screenshot({ path: testInfo.outputPath('settings-no-js.png'), fullPage: true })
  await native.goto('/?return_to=https%3A%2F%2Fevil.example%2F')
  await expect(native.getByText('That return address is not allowed.')).toBeVisible()
  await expect(native.locator('a[href^="https://evil.example"]')).toHaveCount(0)
  await context.close()

  await page.goto('/recovery')
  await expect(page.getByRole('heading', { name: 'Reset your password' })).toBeVisible()
  await page.getByLabel('Email').fill(`unknown-${randomUUID()}@example.test`)
  await page.getByRole('button', { name: 'Send recovery email' }).click()
  await expect(page.getByText('If an account exists for that email, a recovery link is on its way.')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('recovery-mobile.png'), fullPage: true })

  await page.goto('/login')
  await page.getByLabel('Email').fill('reader@tadoku.app')
  await page.getByLabel('Password').fill(initialPassword)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await page.getByLabel('Display name').fill('W2 Dev Reader')
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByText('Profile saved.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Display name')).toHaveValue('W2 Dev Reader')
  await page.getByLabel('Email').fill('dev@tadoku.app')
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByText('This email is already registered.')).toBeVisible()
  await page.getByLabel('New password').fill('reader@tadoku.app')
  await page.getByRole('button', { name: 'Save password', exact: true }).click()
  await expect(page.getByText('Use at least 8 characters, at most 72 UTF-8 bytes, and a password different from your email.')).toBeVisible()

  const oldSession = await browser.newContext({ baseURL: testInfo.project.use.baseURL })
  const oldPage = await oldSession.newPage()
  await oldPage.goto('/login')
  await oldPage.getByLabel('Email').fill('reader@tadoku.app')
  await oldPage.getByLabel('Password').fill(initialPassword)
  await oldPage.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(oldPage.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()

  const admin = await browser.newContext({ baseURL: testInfo.project.use.baseURL })
  const adminPage = await admin.newPage()
  await adminPage.goto('/login')
  await adminPage.getByLabel('Email').fill('dev@tadoku.app')
  await adminPage.getByLabel('Password').fill(process.env.AUTHV2_ADMIN_PASSWORD || 'tadoku')
  await adminPage.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(adminPage.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()

  const origin = new URL(testInfo.project.use.baseURL as string)
  const mainOrigin = origin.origin.replace('.authv2.', '.')
  const destination = `${mainOrigin}/pages/dev-welcome?w2=complete#main`
  await page.goto(`/recovery?return_to=${encodeURIComponent(destination)}`)
  await page.getByLabel('Email').fill('reader@tadoku.app')
  await page.getByRole('button', { name: 'Send recovery email' }).click()
  await expect(page.getByText('If an account exists for that email, a recovery link is on its way.')).toBeVisible()
  let emailId: string | undefined
  await expect.poll(async () => {
    const list = await admin.request.get(`${mainOrigin}/api/internal/emails?recipient=reader%40tadoku.app&template=account.recovery&status=held`)
    expect(list.status()).toBe(200)
    emailId = (await list.json()).emails[0]?.id
    return emailId
  }, { timeout: 30_000 }).toBeTruthy()
  const detail = await admin.request.get(`${mainOrigin}/api/internal/emails/${emailId}`)
  expect(detail.status()).toBe(200)
  const message = await detail.json()
  expect(message.status).toBe('held')
  const generatedLink: string = message.params.recovery_url
  expect(message.body.includes(generatedLink)).toBe(true)
  expect(new URL(generatedLink).origin).toBe(mainOrigin)
  await page.goto(generatedLink)
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('return_to')).toBe(destination)
  const replacement = `Replacement-${randomUUID()}`
  await page.getByLabel('New password').fill(replacement)
  await page.getByRole('button', { name: 'Save password and continue' }).click()
  await page.waitForURL(destination)
  if (stateFile) writeFileSync(stateFile, replacement, { mode: 0o600 })
  await oldPage.goto('/')
  await expect(oldPage.getByRole('heading', { name: 'Log in', exact: true })).toBeVisible()
  await page.goto(origin.origin)
  await page.getByRole('button', { name: 'Log out', exact: true }).click()
  await page.getByLabel('Email').fill('reader@tadoku.app')
  await page.getByLabel('Password').fill(initialPassword)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(page.getByText('The email or password is incorrect.')).toBeVisible()
  await page.getByLabel('Email').fill('reader@tadoku.app')
  await page.getByLabel('Password').fill(replacement)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('recovered-settings.png'), fullPage: true })
  expect((await admin.request.get(generatedLink, { maxRedirects: 0 })).status()).toBe(400)
  await oldSession.close()
  await admin.close()
})
