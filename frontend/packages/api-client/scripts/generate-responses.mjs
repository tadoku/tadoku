// Writes src/generated/responses.gen.ts: each operation's documented success statuses and whether each has a body.
// `pnpm --filter api-client generate` runs it after openapi-ts, from the same canonical contract.
import { readFileSync, writeFileSync } from 'node:fs'
import { load } from 'js-yaml'
import config from '../openapi-ts.config.mjs'

const root = new URL('../', import.meta.url)
const spec = load(readFileSync(new URL(config.input, root), 'utf8'))

const entries = Object.entries(spec.paths).flatMap(([path, item]) =>
  Object.entries(item).map(([method, operation]) => {
    const statuses = Object.entries(operation.responses)
      .filter(([status]) => /^2\d\d$/.test(status))
      .map(([status, response]) => {
        const resolved = response.$ref ? spec.components.responses[response.$ref.split('/').pop()] : response
        return `${status}: ${Object.keys(resolved.content ?? {}).length > 0}`
      })
    return `  '${method.toUpperCase()} ${path}': ${statuses.length ? `{ ${statuses.join(', ')} }` : '{}'},`
  }))

writeFileSync(new URL('src/generated/responses.gen.ts', root), `// This file is auto-generated by scripts/generate-responses.mjs

/** Each operation's documented success statuses, keyed by method and path, and whether each answer has a body. */
export const successResponses: Readonly<Record<string, Readonly<Record<number, boolean>>>> = {
${entries.join('\n')}
}
`)
