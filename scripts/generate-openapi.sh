#!/usr/bin/env bash
set -euo pipefail

API_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SPEC="$API_ROOT/services/tadoku-api/spec"
FRAGMENTS="$SPEC/openapi"
# Contract order: it fixes the operation and schema order of the documentation views.
PATH_FRAGMENTS=(
  authz
  content-pages
  content-posts
  content-announcements
  immersion-contests
  immersion-contest-events
  immersion-logs
  immersion-profiles
  immersion-leaderboards
  immersion-scoring
  immersion-feature-flags
  immersion-languages
  profile
  authz-proxy
  identity
  identity-settings
  email
  identity-proxy
)
SCHEMA_FRAGMENTS=(
  authz
  content
  immersion
  immersion-contests
  immersion-contest-events
  immersion-scoring
  immersion-logs
  profile
  authz-proxy
  identity
  email
  identity-proxy
)

ROOT_BAZEL_VERSION="$(tr -d '[:space:]' <"$API_ROOT/.bazelversion")"
OAPI_BAZEL_VERSION="$(tr -d '[:space:]' <"$API_ROOT/tools/oapi-codegen/.bazelversion")"
if [[ "$ROOT_BAZEL_VERSION" != "$OAPI_BAZEL_VERSION" ]]; then
  echo "tools/oapi-codegen/.bazelversion ($OAPI_BAZEL_VERSION) must match root .bazelversion ($ROOT_BAZEL_VERSION)" >&2
  exit 1
fi

listed="$(printf '%s\n' root.yaml components.yaml)
$(printf 'paths/%s.yaml\n' "${PATH_FRAGMENTS[@]}")
$(printf 'schemas/%s.yaml\n' "${SCHEMA_FRAGMENTS[@]}")"
found="$(cd "$FRAGMENTS" && find . -type f | sed 's|^\./||')"
if [[ "$(sort <<<"$listed")" != "$(sort <<<"$found")" ]]; then
  echo "List every contract fragment in $FRAGMENTS in scripts/generate-openapi.sh, in contract order" >&2
  exit 1
fi

fragment_body() {
  local file="$FRAGMENTS/$1"
  shift
  if [[ "$(head -n $# "$file")" != "$(printf '%s\n' "$@")" ]]; then
    echo "$file must start with the section header: $*" >&2
    exit 1
  fi
  tail -n +$(($# + 1)) "$file"
}

bundle_openapi() {
  echo "# Generated by ./scripts/generate-openapi.sh from services/tadoku-api/spec/openapi/. Do not edit."
  cat "$FRAGMENTS/root.yaml"
  echo "paths:"
  for name in "${PATH_FRAGMENTS[@]}"; do
    fragment_body "paths/$name.yaml" "paths:"
  done
  printf 'components:\n  schemas:\n'
  for name in "${SCHEMA_FRAGMENTS[@]}"; do
    fragment_body "schemas/$name.yaml" "components:" "  schemas:"
  done
  fragment_body components.yaml "components:"
}

bundle="$(mktemp)"
trap 'rm -f "$bundle"' EXIT
bundle_openapi >"$bundle"
cat "$bundle" >"$SPEC/openapi.yaml"

(
  cd "$API_ROOT/tools/oapi-codegen"
  bazel run --lockfile_mode=error @com_github_oapi_codegen_oapi_codegen_v2//cmd/oapi-codegen -- \
    -config "$SPEC/server-codegen.yaml" \
    -o "$API_ROOT/services/tadoku-api/generated/openapi/api.gen.go" \
    "$SPEC/openapi.yaml"
  bazel run --lockfile_mode=error @com_github_oapi_codegen_oapi_codegen_v2//cmd/oapi-codegen -- \
    -config "$SPEC/callback-server-codegen.yaml" \
    -o "$API_ROOT/services/tadoku-api/generated/openapi/callback/api.gen.go" \
    "$SPEC/openapi.yaml"
)
